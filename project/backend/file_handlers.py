import docx
import fitz  # PyMuPDF for PDF
from pptx import Presentation
from pdf2docx import Converter
import subprocess
import shutil
import logging
import os
from typing import Dict, List, Any

logger = logging.getLogger(__name__)

from .config import LIBREOFFICE_PATH


def read_docx_enhanced(file_path: str) -> str:
    try:
        doc = docx.Document(file_path)
        content = []
        for paragraph in doc.paragraphs:
            if paragraph.text.strip():
                content.append(paragraph.text.strip())
        for table in doc.tables:
            for row in table.rows:
                row_data = []
                for cell in row.cells:
                    if cell.text.strip():
                        row_data.append(cell.text.strip())
                if row_data:
                    content.append(" | ".join(row_data))
        return "\n\n".join(content)
    except Exception as e:
        logger.error(f"Error reading DOCX: {str(e)}")
        return ""

def read_pdf_enhanced(file_path: str) -> str:
    try:
        doc = fitz.open(file_path)
        content = []
        for page_num in range(len(doc)):
            page = doc[page_num]
            blocks = page.get_text("dict")["blocks"]
            for block in blocks:
                if "lines" in block:
                    block_text = ""
                    for line in block["lines"]:
                        for span in line["spans"]:
                            block_text += span["text"] + " "
                    block_text = block_text.strip()
                    if block_text and len(block_text) > 10:
                        content.append(block_text)
        doc.close()
        return "\n\n".join(content)
    except Exception as e:
        logger.error(f"Error reading PDF: {str(e)}")
        return ""

def read_pptx_enhanced(file_path: str) -> str:
    try:
        prs = Presentation(file_path)
        content = []
        for slide_num, slide in enumerate(prs.slides, 1):
            slide_content = []
            for shape in slide.shapes:
                if hasattr(shape, "text") and shape.text.strip():
                    slide_content.append(shape.text.strip())
            if slide_content:
                content.append(f"Slide {slide_num}:\n" + "\n".join(slide_content))
        return "\n\n".join(content)
    except Exception as e:
        logger.error(f"Error reading PPTX: {str(e)}")
        return ""

def validate_formatting_preservation(original_path: str, translated_path: str) -> Dict[str, Any]:
    try:
        original_doc = docx.Document(original_path)
        translated_doc = docx.Document(translated_path)
        validation_results = {
            'paragraph_count_match': len(original_doc.paragraphs) == len(translated_doc.paragraphs),
            'table_count_match': len(original_doc.tables) == len(translated_doc.tables),
            'style_preservation': True,
            'issues': []
        }
        for i, (orig_para, trans_para) in enumerate(zip(original_doc.paragraphs, translated_doc.paragraphs)):
            if orig_para.style != trans_para.style:
                validation_results['style_preservation'] = False
                validation_results['issues'].append(f"Paragraph {i} style mismatch")
            if orig_para.alignment != trans_para.alignment:
                validation_results['style_preservation'] = False
                validation_results['issues'].append(f"Paragraph {i} alignment mismatch")
        return validation_results
    except Exception as e:
        return {
            'paragraph_count_match': False,
            'table_count_match': False,
            'style_preservation': False,
            'issues': [f"Validation failed: {e}"]
        }

def convert_pdf_to_docx(pdf_path: str) -> str:
    try:
        docx_path = os.path.splitext(pdf_path)[0] + '.docx'
        cv = Converter(pdf_path)
        cv.convert(docx_path)
        cv.close()
        return docx_path
    except Exception as e:
        logger.error(f"PDF to DOCX conversion failed: {str(e)}")
        return None

def convert_docx_to_pdf(docx_path: str, libreoffice_path: str = LIBREOFFICE_PATH) -> str:
    output_dir = None
    try:
        output_dir = os.path.join(os.path.dirname(docx_path), "temp_pdf")
        os.makedirs(output_dir, exist_ok=True)
        args = [
            libreoffice_path,
            '--headless',
            '--convert-to',
            'pdf',
            '--outdir',
            output_dir,
            docx_path
        ]
        subprocess.check_call(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        pdf_filename = os.path.splitext(os.path.basename(docx_path))[0] + '.pdf'
        generated_pdf = os.path.join(output_dir, pdf_filename)
        if not os.path.exists(generated_pdf):
            raise FileNotFoundError("PDF file was not generated by LibreOffice")
 
        # Copy to safe location
        safe_output = os.path.join(os.path.dirname(docx_path), pdf_filename)
        shutil.copyfile(generated_pdf, safe_output)
 
        return safe_output
 
    except Exception as e:
        logger.error(f"DOCX to PDF conversion failed: {str(e)}")
        return None
    finally:
        if output_dir and os.path.exists(output_dir):
            shutil.rmtree(output_dir, ignore_errors=True)

def extract_text_from_file(file_path: str, ext: str) -> str:
    if ext == ".docx":
        return read_docx_enhanced(file_path)
    elif ext == ".pdf":
        return read_pdf_enhanced(file_path)
    elif ext == ".pptx":
        return read_pptx_enhanced(file_path)
    return ""